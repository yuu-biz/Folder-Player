def main():
    keys = base_keys()
    ok = True
    for lang, table in T.items():
        table = {k: v for k, v in table.items() if k in keys or k not in DROPPED}
        missing = [k for k in keys if k not in table]
        extra = [k for k in table if k not in keys]
        pmiss = [k for k in base_plurals() if k not in P[lang] or any(q not in P[lang][k] for q in QUANTITIES[lang])]
        missing += pmiss
        if missing or extra:
            print(f"{lang}: missing={missing} extra={extra}", file=sys.stderr)
            ok = False
            continue
        d = os.path.join(RES, f"values-{lang}")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/i18n/gen_translations.py; edit the table there. -->\n<resources>\n')
            for k in keys:
                f.write(f'    <string name="{k}">{esc(table[k])}</string>\n')
            for k in base_plurals():
                f.write(f'    <plurals name="{k}">\n')
                for q in QUANTITIES[lang]:
                    f.write(f'        <item quantity="{q}">{esc(P[lang][k][q])}</item>\n')
                f.write("    </plurals>\n")
            f.write("</resources>\n")
        print(f"wrote values-{lang} ({len(keys)} strings, {len(base_plurals())} plurals)")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
