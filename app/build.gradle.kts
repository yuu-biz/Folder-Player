// FFmpeg static libraries are rebuilt from the pinned source tarball when missing (Linux/WSL with the NDK).
val buildFfmpeg by tasks.registering(Exec::class) {
    val out = rootProject.file("native/out")
    onlyIf { !File(out, "arm64-v8a/lib/libavcodec.a").exists() || !File(out, "x86_64/lib/libavcodec.a").exists() }
    workingDir = rootProject.projectDir
    commandLine("bash", "native/build-ffmpeg.sh")
}
tasks.matching { it.name.startsWith("configureCMake") || it.name.startsWith("buildCMake") }.configureEach { dependsOn(buildFfmpeg) }

// Prints the unit-test runtime classpath so protocol tests that need the Docker network (DLNA multicast) can run
// inside a JVM container: scripts/fixtures/run-in-network-tests.sh
tasks.register("printUnitTestClasspath") {
    // The FileCollection carries the build dependencies of its jars/class dirs (not of the test task itself).
    val cp = tasks.named<Test>("testDebugUnitTest").get().classpath
    dependsOn(cp)
    doLast { println("CP=" + cp.asPath) }
}
