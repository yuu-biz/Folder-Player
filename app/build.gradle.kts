        versionCode = (project.findProperty("fpVersionCode") as String?)?.toInt() ?: 501
        versionName = (project.findProperty("fpVersionName") as String?) ?: "0.5.0-fork.1"
        resValue("string", "app_name", "Folder Player Fork")

